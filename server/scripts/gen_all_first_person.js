async function geminiImage(prompt) {
  const url = 'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-image:generateContent?key=' + apiKey;
  const body = {
    contents: [{ parts: [{ text: prompt }] }],
    generationConfig: { responseModalities: ['IMAGE', 'TEXT'], temperature: 0.85 },
  };
  const resp = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  if (!resp.ok) throw new Error('API ' + resp.status + ': ' + (await resp.text()).slice(0, 300));
  const data = await resp.json();
  const parts = data.candidates && data.candidates[0] && data.candidates[0].content && data.candidates[0].content.parts;
  if (!parts) throw new Error('応答にcontent.partsなし');
  for (const p of parts) {
    const inline = p.inlineData || p.inline_data;
    if (inline && inline.data) return Buffer.from(inline.data, 'base64');
  }
  throw new Error('画像が返ってきませんでした');
}

(async () => {
  const onlyArg = process.argv.find(a => a.startsWith('--only='));
  const only = onlyArg ? onlyArg.replace('--only=', '').split(',') : null;
  const targets = only ? FLOORS.filter(f => only.includes(f.code)) : FLOORS;
  console.log(`生成対象 ${targets.length} フロア:`, targets.map(t => t.code).join(', '));
  for (const f of targets) {
    try {
      console.log(`\n━━ [${f.code}] ${f.label} 生成中…`);
      const fullPrompt = f.prompt + '\n' + COMMON_REQUIREMENTS;
      const buf = await geminiImage(fullPrompt);
      if (fs.existsSync(f.out)) fs.copyFileSync(f.out, f.out + '.bak.' + Date.now());
      const tmpRaw = f.out + '.raw';
      fs.writeFileSync(tmpRaw, buf);
      execSync(`ffmpeg -y -i ${tmpRaw} -vf "crop=in_w:in_w*9/16:0:(in_h-in_w*9/16)/2,scale=1344:768" -update 1 -frames:v 1 ${f.out}`, { stdio: 'pipe' });
      fs.unlinkSync(tmpRaw);
      console.log(`✅ [${f.code}] 完了: ${f.out}`);
    } catch (e) {
      console.error(`❌ [${f.code}] 失敗:`, e.message);
    }
    // API 過負荷回避で 2 秒待機
    await new Promise(r => setTimeout(r, 2000));
  }
  console.log('\n✨ 全フロア生成完了');
})().catch(e => { console.error(e); process.exit(2); });
